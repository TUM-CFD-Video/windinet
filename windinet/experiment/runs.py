"""Per-run records: what produced a run (provenance) and the index of a results stage.

A run folder holds config.yaml (the resolved config: name, description, every setting; re-runnable as is),
metrics.json (the outcome, plus the provenance block) and the figures and weights. The index README.md
of a stage folder is generated from those files; edit a description in config.yaml, not in the index.
"""

from __future__ import annotations

import json
import platform
import shlex
import subprocess
import sys
import time
from pathlib import Path

import yaml

from windinet.eulermq.data import FIELDS, SYMBOLS


def provenance(started: float, world: int = 1) -> dict:
    """Code version, command, library versions, GPUs and wall time of the run that is finishing now."""
    import diffusers  # imported here: the index script needs neither
    import torch

    def git(*args: str) -> str | None:
        try:
            return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout.strip()
        except (subprocess.CalledProcessError, FileNotFoundError):
            return None

    return {
        "commit": git("rev-parse", "--short", "HEAD"),
        "dirty": bool(git("status", "--porcelain", "--", "windinet", "scripts", "configs")),
        "command": "python " + shlex.join(sys.argv),  # quoted, so it pastes back into a shell
        "python": platform.python_version(),
        "torch": str(torch.__version__),  # a str subclass that yaml cannot dump
        "diffusers": diffusers.__version__,
        "gpu": f"{world} x " + (torch.cuda.get_device_name() if torch.cuda.is_available() else "cpu"),
        "started": time.strftime("%Y-%m-%d %H:%M", time.localtime(started)),
        "seconds": round(time.time() - started),
    }


def write_config(cfg: dict, path: Path) -> None:
    """The resolved config as YAML, with a header on how to re-run it."""
    head = f"# {cfg['name']}: {cfg.get('description', '')}\n# Re-run: python {sys.argv[0]} {path} --name <new name>\n"
    path.write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=200))


def settings(cfg: dict) -> str:
    """One phrase per run: from what and how long it was trained; the stage's choices are in its config.yaml."""
    train, load = cfg.get("train", {}), cfg.get("load")
    parts = [f"from {Path(load).name}" + (f" @ {cfg['load_step']}" if cfg.get("load_step") else "")] if load else []
    if train.get("steps"):
        parts.append(f"{train['steps']} steps, lr {train.get('lr', 0):g}, batch {train.get('batch_sims', 1)}")
    else:
        parts.append("eval only")
    return ", ".join(parts)


def run_row(run_dir: Path, label: str) -> list[str] | None:
    """One index row of a run (or of a stage nested in a run: `label` is its path from the stage dir)."""
    metrics_path = run_dir / "metrics.json"
    if not metrics_path.exists():
        return None
    metrics = json.loads(metrics_path.read_text())
    config_path = run_dir / "config.yaml"
    cfg = yaml.safe_load(config_path.read_text()) if config_path.exists() else metrics["config"]
    final = metrics["final"]
    vrmse = [final.get(f"vrmse_{f}") for f in FIELDS]  # None for a field the run's groups drop
    present = [v for v in vrmse if v is not None]
    prov = metrics.get("provenance", {})
    return [
        f"[{label}]({label}/)",
        cfg.get("description", ""),
        settings(cfg),
        *(f"{v:.3f}" if v is not None else "–" for v in vrmse),
        f"{final.get('vrmse_mean', sum(present) / len(present)):.3f}"
        + (f" ± {final['vrmse_std']:.3f}" if "vrmse_std" in final else ""),
        *(f"{final[k]:.3f}" if k in final else "–" for k in ("h1_mean", "ssim_mean")),
        (prov.get("commit") or "") + (" (dirty)" if prov.get("dirty") else ""),  # no git: commit is None
    ]


def write_index(stage_dir: Path) -> Path:
    """README.md of a stage: one row per run folder, from config.yaml + metrics.json; a run's continuations and
    evaluations (nested folders, `--name <run>/<stage>`) follow their run."""
    rows = []
    for d in sorted(p for p in stage_dir.iterdir() if p.is_dir()):
        rows += [r] if (r := run_row(d, d.name)) else []
        rows += [r for s in sorted(d.iterdir()) if s.is_dir() and (r := run_row(s, f"{d.name}/{s.name}"))]
    head = ["run", "description", "settings", *SYMBOLS.values(), "mean ± std over sims", "H1", "SSIM", "commit"]
    lines = [
        f"# Runs in `{stage_dir}`",
        "",
        "Generated by `scripts/wan/index_runs.py` from each run's config.yaml and metrics.json; do not edit.",
        "VRMSE per field on the test simulations in physical units (0.05 = 5 % of the field's spread), averaged over",
        "the simulations; ± is the std over simulations of the field mean. H1 = relative gradient error, SSIM as",
        "Wang et al. (rollouts; the other metrics are in metrics.json). Each folder holds config.yaml",
        "(re-runnable), metrics.json, panel.png, curves.png, adapter.pt and, for VAE fine-tunes, vae.pt (not in git).",
        "A row `run/stage` is a continuation or evaluation of `run` (its own config.yaml names `load`).",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    path = stage_dir / "README.md"
    path.write_text("\n".join(lines) + "\n")
    return path
